import { test, expect } from "@playwright/test";
import JSZip from "jszip";
import { readFile } from "node:fs/promises";

test("button edit, undo, safe preview navigation, reload and ZIP", async ({ page }) => {
  await page.goto("/#create");
  await page.getByRole("button", { name: "샘플 미리보기 만들기" }).click();
  await page.getByRole("button", { name: "편집으로 돌아가기" }).click();
  await page.getByRole("button", { name: "버튼 추가", exact: true }).click();
  await expect(page.locator(".db-action")).toHaveCount(1);
  await page.getByRole("button", { name: "실행 취소" }).click();
  await expect(page.locator(".db-action")).toHaveCount(0);
  await page.getByRole("button", { name: "버튼 추가", exact: true }).click();
  await page.getByLabel("버튼 문구", { exact: true }).fill("현황 확인");
  await page.getByLabel("버튼 스타일", { exact: true }).selectOption("danger");
  await page.getByLabel("버튼 크기", { exact: true }).selectOption("large");
  await page.getByLabel("이동 주소", { exact: true }).fill("javascript:alert(1)");
  await page.getByRole("button", { name: "변경 적용", exact: true }).click();
  await expect(page.locator(".db-action")).toHaveAttribute("href", "#dashboard-data");
  await expect(page.getByLabel("이동 주소", { exact: true })).toHaveValue("javascript:alert(1)");
  await page.getByLabel("이동 주소", { exact: true }).fill("#dashboard-data");
  await page.getByRole("button", { name: "변경 적용", exact: true }).click();
  await page.getByRole("button", { name: "미리보기", exact: true }).click();
  const url = page.url();
  await page.getByRole("link", { name: "현황 확인", exact: true }).click();
  await expect(page).toHaveURL(url);
  await expect(page.locator(".workspace-preview")).toBeVisible();
  await page.reload();
  await expect(page.locator(".db-action")).toHaveText("현황 확인");
  await expect(page.locator(".db-action")).toHaveClass(/db-action-danger db-action-large/);
  await page.getByRole("button", { name: "확정 및 다운로드" }).click();
  await expect(page.getByText("모든 검사를 통과했습니다.")).toBeVisible();
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "ZIP 다운로드", exact: true }).click();
  const download = await downloadPromise;
  const zip = await JSZip.loadAsync(await readFile((await download.path())!));
  const html = await zip.file("index.html")!.async("string");
  expect(html).toContain('href="#dashboard-data"');
  expect(html).toContain('id="dashboard-data"');
  expect(html).toContain("현황 확인");
});
